#define STATUS_PRINT_INTERVAL_S 0.5f

// ===========================================================================
// 実行時間プロファイル (DWTサイクルカウンタ)
// ===========================================================================
// 20kHzの制御ループが1回あたり何µs使っているかを実測する。
// 制御周期を上げる/処理を足す前に、まずここで余裕を確認すること。
//   0 : 無効 (計測コードごとコンパイルされない)
