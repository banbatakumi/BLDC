#define PROFILE_ISR 2

// プロファイルの表示間隔 [s]。0 で表示しない。
// 表示は printf (USART1, ブロッキング) なのでメインループだけが待たされる。
// 制御ループは割り込み優先度0で走っているので影響を受けない。
#define PROFILE_PRINT_INTERVAL_S 1.0f

// ===========================================================================
// PWM / 制御周期
// ===========================================================================
// TIM1 は**センター揃え** (アップダウンカウント)。
//   1周期 = 2 × ARR カウント → 72MHz / (2 × 1800) = 20kHz
//   デューティ = CCR / ARR
// エッジ揃えの頃は「ARR+1 で割る」だったので式が違う。ARR を触るときは注意。
// センター揃えにした理由と効果は docs/OPTIMIZATION.md の3番を参照。
#define PWM_ARR 1800
#define PWM_FREQ 20000.0f  // PWM周波数 = 電流ループ周波数 [Hz]

// デッドタイム [カウント]。tim.c の sBreakDeadTimeConfig.DeadTime と一致させること。
// DTG = 20, tDTS = 1/72MHz なので 20 × 13.9ns = 278ns。
#define PWM_DEADTIME_COUNTS 20

#define CURRENT_LOOP_DT (1.0f / PWM_FREQ)  // 電流ループ周期 [s] (50µs)

// 外側ループはADC完了割り込みを分周して回す
// (角速度は分周せず、20kHzの角度追従オブザーバから直接得る)
#define OUTER_LOOP_DIV 20   // 速度/位置制御 → 1kHz
#define ACCEL_CALC_DIV 400  // 角加速度計算 → 50Hz

#define OUTER_LOOP_DT (CURRENT_LOOP_DT * OUTER_LOOP_DIV)
#define ACCEL_CALC_DT (CURRENT_LOOP_DT * ACCEL_CALC_DIV)

// ---------------------------------------------------------------------------
// デューティの上限 (センター揃えの肝)
// ---------------------------------------------------------------------------
// ローサイドシャントは低側FETがONの区間しか相電流が流れない。
// センター揃えではこの区間が**カウンタ頂点を中心に左右対称**に広がる。
//
//   上りで CNT = CCR を通過 → デッドタイム後に低側ON
//   CNT = PWM_ARR (頂点) で折り返し
//   下りで CNT = CCR を通過 → 低側OFF
//   片側の幅 = (PWM_ARR - CCR) カウント
//
// エッジ揃えだった頃は区間 [CCR, ARR] の**後ろ側しか使えず**、サンプリング点より
// 手前のデューティしか出せなかった (MAX_DUTY = 0.80)。センター揃えでは同じ絶対時間の
// 余裕が頂点の両側に分かれるので、上限を引き上げられる。
//
// 上限は「頂点の手前側」に必要な時間が収まるかで決まる:
//   必要 = デッドタイム + アンプ整定 + トリガ前倒し
//        = 20 + 144 + 50 = 214 カウント
//   使える = PWM_ARR × (1 - MAX_DUTY) = 1800 × 0.12 = 216 カウント  ✓
//
// 整定時間 144カウント (2.0µs) の根拠:
//   INA181A1 は帯域 350kHz の1次系なので τ = 1/(2π×350k) = 455ns。
//   1%整定 = 4.6τ = 2.1µs。データシートの実測は 1.6µs typ なので 2.0µs は保守側。
//   **オシロで実測した値ではない。** 実測すれば 0.92 程度まで引ける見込みがあるが、
//   外すと「高デューティ域だけ電流値が嘘をつく」という切り分けの難しい壊れ方をするので
//   余裕を残してある。詰めたくなったら docs/OPTIMIZATION.md の「ADCで整定時間を測る」を参照。
#define CURRENT_SENSE_SETTLING_COUNTS 144

// 上限・下限は**CCRのカウント数**で定義し、デューティはそこから導く。
// float を (int) にキャストした値は整数定数式にならず _Static_assert に使えないため。
// カウント数のほうが物理的にも本質 (実際にハードウェアが比較するのはこの値)。
#define MAX_DUTY_CCR 1584  // 1584 / 1800 = 0.880
#define MIN_DUTY_CCR 36    //   36 / 1800 = 0.020

#define MAX_DUTY ((float)MAX_DUTY_CCR / (float)PWM_ARR)
#define MIN_DUTY ((float)MIN_DUTY_CCR / (float)PWM_ARR)

// 電圧ベクトルの大きさの上限 (対 母線電圧)。
// SVPWM(三次高調波重畳)なので相電圧振幅は (MAX_DUTY - 0.5) * 2/√3 まで出せる。
#define MAX_MODULATION_RATIO ((MAX_DUTY - 0.5f) * 1.1547005f)

// ===========================================================================
// 電流センシング (ローサイドシャント + 双方向電流センスアンプ INA181A1)
// ===========================================================================
//   回路: CurcuitV4  R16/R24 = 5mΩ,  U4/U6 = INA181A1
//   REF は R28-R31 の 1k/1k 分圧で 3.3V/2 = 1.65V に固定されているので、
//   無電流時の出力は約1.65V = ADC 2048 になり、正負どちらの電流も読める。
#define SHUNT_RESISTANCE 0.005f  // シャント抵抗 [Ω]
#define CURRENT_AMP_GAIN 20.0f   // 電流センスアンプ INA181A1 のゲイン [V/V]

#define CURRENT_REF_ADC 2048.0f       // 無電流時の出力(理論値) [ADC]
#define CURRENT_OFFSET_TOLERANCE 250  // オフセット校正値の許容ずれ [ADC]

// ADCのトリガ位置。カウンタ頂点から何カウント手前で叩くか。
// TIM1_CH4 を PWM2 モードにして CCR4 = PWM_ARR - この値 とし、
// OC4REF → TRGO2 → ADC1外部トリガ とする。上りで1回だけ立ち上がる。
//
// 低側ON区間の中央 = カウンタ頂点でサンプリングすると、三角波リプルの平均値が
// そのまま取れる (瞬時値ではなく1周期の平均電流になる)。ADCは2ch連続変換なので、
// 2回のサンプリングが頂点をまたぐように少し手前で叩く。
//   1ch目: サンプリング 61.5 + 変換 12.5 = 74 ADCサイクル
//   2ch目: 同上 → トリガから2ch目のサンプリング終了まで 74 + 61.5 = 135.5 サイクル
//   ADCクロック 72MHz なので 1.88µs = 135 カウント。中央は 68 カウント手前。
// ただし上の整定時間の制約のほうが厳しいので 50 にしている。
// (取得区間の中心は頂点の 18 カウント = 0.25µs 後ろ。ほぼ中央なので実害なし)
#define CURRENT_SENSE_TRIG_ADVANCE 50

// トリガから2ch目のサンプリングが終わるまで [カウント]。
// (61.5+12.5) + 61.5 = 135.5 ADCサイクル、ADCもタイマも72MHzなので同じ数
#define CURRENT_SENSE_ACQ_COUNTS 135

// --- 設定の整合をコンパイル時に検査する ---
// PWM周波数・MAX_DUTY・トリガ位置・サンプリング時間は互いに縛り合っている。
// どれか1つを触ると静かに壊れる (電流値だけが嘘になり、症状からは原因が見えない) ので、
// 関係式をここに書いてビルドで落ちるようにしておく。

// メッセージがASCIIなのはわざと。GCCは _Static_assert の文字列の非ASCIIを
// 8進エスケープに潰してしまい、日本語で書くとエラーが読めなくなる。

// (1) 頂点の手前側: 低側FETがONしてアンプが整定してからトリガが来ること
_Static_assert((PWM_ARR - CURRENT_SENSE_TRIG_ADVANCE) - (MAX_DUTY_CCR + PWM_DEADTIME_COUNTS) >=
                   CURRENT_SENSE_SETTLING_COUNTS,
               "MAX_DUTY_CCR too high: ADC samples before the current amp settles. "
               "Lower MAX_DUTY_CCR or CURRENT_SENSE_TRIG_ADVANCE.");

// (2) 頂点の奥側: 2ch目のサンプリングが終わる前に低側FETがOFFにならないこと
_Static_assert((CURRENT_SENSE_ACQ_COUNTS - CURRENT_SENSE_TRIG_ADVANCE) <=
                   (PWM_ARR - MAX_DUTY_CCR),
               "ADC acquisition runs past the low-side ON window. "
               "Raise CURRENT_SENSE_TRIG_ADVANCE or lower MAX_DUTY_CCR/sampling time.");

// (3) 下限が上限を下回っていること
_Static_assert(MIN_DUTY_CCR >= 0 && MIN_DUTY_CCR < MAX_DUTY_CCR && MAX_DUTY_CCR < PWM_ARR,
               "Duty CCR limits are inconsistent.");

// (3) トリガ位置がカウンタ範囲に収まっていること
_Static_assert(CURRENT_SENSE_TRIG_ADVANCE > 0 && CURRENT_SENSE_TRIG_ADVANCE < PWM_ARR,
               "CURRENT_SENSE_TRIG_ADVANCEが範囲外");

// 割り込みがこの時間を超えるとデューティの反映が1周期ずれる [µs]。
//
// CCRはプリロード付き (HALがPWMモードでOCxPEを立てる) なので、書き込みは次の
// 更新イベントで反映される。センター揃えでは更新イベントが**頂点と谷の両方**で
// 起きるため、割り込みが長引いて書き込みが谷を過ぎてから届くと、
// 次の「頂点」で反映されてしまう。そうなると低側ON区間が左右非対称になり、
// せっかく頂点に合わせたサンプリング点がずれる。
//
//   頂点 → 2ch目の変換完了 = 148 - 50 = 98カウント = 1.36µs
//   頂点 → 谷 = PWM_ARR = 1800カウント = 25.0µs
//   → 割り込みに使える時間 = 25.0 - 1.36 - (DMAと割り込み応答 約0.2µs) = 23.4µs
//
// PROFILE_ISR を有効にすると irq の最大値がこれを超えたときに警告が出る。
#define ISR_DEADLINE_US 23.4f

// 電流の符号
//   INA181の IN+(pin3) が下側FETのソース(シャント上側)、IN-(pin4) が GNDPWR に繋がっている。
//   相電流がインバータからモータへ流れ出す向き(正)のとき、電流は
//   GNDPWR → シャント → 下側FET → モータ と流れるのでシャント上側は GNDPWR より
//   低電位になり、アンプ出力は REF より下がる。
//   よって「(ADC値 - オフセット) × -1」が相電流になる。
#define CURRENT_SIGN (-1.0f)

// 測定電流のローパス係数 (1.0で無フィルタ)。
//   カットオフ fc = fs × -ln(1-a) / 2π   (fs = 20kHz)
//   a=0.25 → 916Hz,  a=0.5 → 2206Hz,  a=0.8 → 5.1kHz
//
// センター揃えにする前は、低側ON区間の**端**でサンプリングしていたので
// 三角波リプルの偏った位置を拾っており、フィルタで均す必要があった。
// いまは区間の**中央**(カウンタ頂点)で拾うので、1サンプルがそのまま
// その周期の平均電流になっている。つまりリプル対策としてのフィルタは不要。
//
// 残る役割はADCノイズとスイッチングノイズの単発スパイク除去だけ。
// 量子化は 0.0081 A/LSB で 7A に対して0.1%なので、フィルタを強くかける理由は薄い。
// 一方でフィルタの位相遅れは電流ループの帯域を直接制限する
// (a=0.25 の 916Hz は、目指す 700Hz の帯域に対して近すぎた)。
// a=0.5 なら 2.2kHz で、700Hz の帯域に対する位相遅れは 17.6° に収まる。
#define CURRENT_LPF_COEF 0.5f

// ===========================================================================
// BLDCのパラメーター
// ===========================================================================
#define POLE_PAIRS 7              // 極対数 (磁石の数/2)
#define MAX_ANGULAR_SPEED 150.0f  // 最大角速度 [rad/s]
#define MAX_ANGULAR_ACCEL 100.0f  // 最大角加速度 [rad/s^2]

// ===========================================================================
// 角度追従オブザーバ (2次PLL)
// ===========================================================================
// 角度を微分して速度を求めるのをやめ、推定角 θ̂ を観測角に追従させるループを
// 回して、その内部状態として θ̂ と ω̂ を同時に得る。
//
//   e   = θ_meas - θ̂                (イノベーション = 観測と推定のずれ)
//   ω̂ += PLL_KI * e * dt            (速度推定 = 積分器)
//   θ̂ += (ω̂ + PLL_KP * e) * dt      (角度推定)
//
// 閉ループは θ̂/θ_meas = (KP·s + KI) / (s² + KP·s + KI) の標準2次系なので
//   固有角周波数 ω_n = √KI  [rad/s]
//   減衰係数     ζ   = KP / (2√KI)
// ζ = 1 (臨界制動 = 行き過ぎない最速) とすると KP = 2·ω_n, KI = ω_n²。
//
// ω_n は観測器の帯域。大きいほど追従が速いがエンコーダのノイズを拾う。
// 速度制御ループ(1kHz)の応答より十分速く、かつノイズを拾わない範囲で選ぶ。
// 整定時間はおよそ 4/ω_n。ζ=1 は下の定義式で自動的に保たれるので、
// 調整するときは PLL_OMEGA_N だけ触ればよい。
//
// 補足: 大きな周波数誤差からの引き込み(ロータを手で急停止させた場合など)は
// PLL_KP がおよその上限になる。PLL_KP ≥ MAX_ANGULAR_SPEED を満たしていれば、
// どの運転速度からでも即座に再ロックできる。
#define PLL_OMEGA_N 200.0f
#define PLL_KP (2.0f * PLL_OMEGA_N)         // 2ζω_n [1/s]
#define PLL_KI (PLL_OMEGA_N * PLL_OMEGA_N)  // ω_n²  [1/s²]

// --- 観測値を棄却する条件 ---
// 「観測できない」と「推定がずれている」を必ず区別すること。混ぜて棄却すると、
// ロータを急停止させたときに θ̂ が ω̂ のまま自走し、その自走を「異常な観測」と
// 誤認して棄却し続ける → 永久にロックが戻らない (脱調したような挙動) となる。

// (a) 飽和の検出 [LSB]。生のADC値がレール付近 = AS5600のアナログ出力の飽和域で、
//     実際に回ってもADC値が変わらない = 角度情報が存在しない。校正で記録した
//     min/max は飽和した値そのものなので、端に張り付いたサンプルを弾けば
//     飽和域を「生の値から確実に」検出できる。よって長めに外挿してよい。
#define ENCODER_EDGE_MARGIN_LSB 4
#define ENCODER_REJECT_MAX 1000  // 1000 × 50µs = 50ms

// (b) イノベーション過大 [rad]。0/2π遷移中のグリッチかもしれないし、推定が
//     本当にずれたのかもしれない。1サンプルでは区別できないので、グリッチが
//     短いことを利用して ENCODER_GLITCH_MAX サンプルだけ様子を見る。
//     続くならグリッチではないので棄却をやめ、PLLに再ロックさせる。
//     ここを打ち切らないと上記の自走から戻れなくなる。
//     値の決め方: 継ぎ目を外挿で渡った直後に残るイノベーション (実測 emax) より
//     十分大きくすること。ここが実測値に近いと、たまたま20サンプル連続で超えた
//     瞬間に再取得モードへ入り、下の積分制限が外れて速度スパイクが復活する。
//     実測 emax ≒ 0.09rad に対し 0.25rad で約2.7倍の余裕を取っている。
//     遷移中のグリッチは中間値を拾うので最大πになり、0.25rad でも確実に捕まる。
#define ENCODER_INNOVATION_LIMIT_RAD 0.25f
#define ENCODER_GLITCH_MAX 20  // 20 × 50µs = 1ms

// 速度推定(積分パス)に渡すイノベーションの上限 [rad]。**ロック中のみ適用する**。
//
// ロック中に残る小さなイノベーションは、エンコーダの継ぎ目の段差(校正誤差)や
// 飽和域を外挿で渡ったときの誤差であって「本物の回転」ではない。これを全量
// 積分に入れると1回転ごとに速度スパイクになり、速度制御がそれに反応する。
// 比例パスには制限をかけないので、段差は角度補正として素早く吸収される。
//
// 逆に、再取得中(ロータを手で急停止させた等)に制限してはいけない。dω̂/dt が
// PLL_KI × 制限値 で頭打ちになり、実際の減速に追従できず脱調状態から戻れなくなる。
// 「ロック中は疑い、ロックを失っていたら信じる」が正しい使い分け。
//
// 値の目安: 実際の角加速度 a による定常イノベーションは a / PLL_KI。
// PLL_OMEGA_N = 250 なら 0.005rad は 312 rad/s² 相当で、指令の加速度制限
// (MAX_ANGULAR_ACCEL = 100 rad/s²) の3倍の余裕がある。
#define PLL_SPEED_ERROR_LIMIT_RAD 0.005f

#define MAX_CURRENT 7.0f         // Id/Iq指令の上限 [A]
#define OVERCURRENT_LIMIT 10.0f  // 過電流保護のしきい値 [A]

// 連続して何サンプルしきい値を超えたら保護を発動するか。
// 1サンプル(50µs)だけのノイズで誤検出しないためのデバウンス。
// 3 なら 150µs 継続した過電流で発動する。
#define OVERCURRENT_TRIP_COUNT 5

// ---------------------------------------------------------------------------
// 電流PI制御のゲイン
// ---------------------------------------------------------------------------
// 設計式:  Kp = L × ω_bw,  Ki = R × ω_bw     (ω_bw = 目標の閉ループ帯域 [rad/s])
//   このとき PIのゼロ点 (Ki/Kp) がプラントの極 (R/L) をちょうど打ち消し、
//   閉ループは帯域 ω_bw の素直な1次系になる。
//
// **KpとKiを同じ倍率で動かせば、LとRを知らなくても帯域だけが倍率どおり動く。**
//   打ち消しの関係 Ki/Kp = R/L が倍率で保たれるため。
//   いまの Ki/Kp = 750/0.75 = 1000 [rad/s] が、このモータの R/L の推定値。
//   L や R の絶対値は分からなくても、これで帯域は思いどおりに動かせる。
//
// 帯域の上限を決めるのは、プラントではなく**位相遅れ**:
//   1.5周期の演算遅れ   : ω_bw × 1.5 × 50µs  (700Hzで18.9°)
//   電流LPF (fc=2.2kHz) : atan(f_bw / 2206)   (700Hzで17.6°)
//   → 700Hz で位相余裕 約53°。**700Hz 前後が現実的な上限。**
//   (6番の演算遅れ補償を入れれば、この上限はもう少し上がる)
//
// **KpとKiを同じ倍率で動かす方式 (旧 CURRENT_BW_SCALE) は使えない。**
// あれは Ki/Kp = R/L が既に成り立っている前提だったが、実測すると
// R/L ≈ 2000〜3000 rad/s に対して Ki/Kp = 1000 rad/s と3倍ずれていた。
// 倍率をかけても「ずれた比を保ったまま」動くだけで、応答は2つの時定数に
// 割れたまま (速い立ち上がり + 1.3ms かけて這い上がる長い尾) になる。
// 必要なのは倍率ではなく**比の修正**で、そのためには L と R の値が要る。
//
// ---------------------------------------------------------------------------
// モータの電気的パラメータ (**フラッシュが空のときの既定値**)
// ---------------------------------------------------------------------------
// 実際に使う値は、スイッチを押しながら起動して自動測定し、フラッシュに保存される。
// ここの値は「まだ一度も校正していない基板で、とりあえず動かすため」の初期値。
// 校正済みならフラッシュの値が優先されるので、ここを直す必要はない。
//
// 2026-07-29 にこのモータで実測した値を入れてある
// (R,L: Vd = 0.4V/0.8V の2点、デッドタイム補正・LPF補正込み)。
// 低インダクタンス・低抵抗のモータなので、電流PIのゲインは小さい値になる。
#define MOTOR_L_DEFAULT 0.000038f  // 相インダクタンス [H] (38 µH)
#define MOTOR_R_DEFAULT 0.1928f    // 相抵抗 [Ω]

// 電流ループの目標帯域 [Hz]。
//
// ここは「設計値」であって実測値ではない。ω_bw = Kp/L という式が
// 理想的な極零相殺と遅れ0を前提にしているのに対し、実際のループには
// 電流LPFと演算遅れが入るので、実測の帯域はこれより2〜3割低く出る。
//
// 700 にしたとき実測 570Hz (補正後) だったので、比率で割り戻して 850 にしてある。
// **上げるときは必ず MEASURE_CURRENT_STEP で確認すること。**
// オーバーシュートが15%を超えたら上げすぎ (いまは 2.3% で余裕がある)。
//
// 位相余裕の予算 (実測700Hzのとき):
//   1.5周期の演算遅れ   : 18.9°
//   電流LPF (fc=2.2kHz) : 17.6°
//   → 位相余裕 約53°
#define CURRENT_BW_HZ 850.0f

// **実際に達成したい**閉ループ帯域 [Hz]。上の CURRENT_BW_HZ とは別物。
//
// 分けているのは、実測を CURRENT_BW_HZ に合わせようとすると追いかけっこに
// なるため。CURRENT_BW_HZ は「実測より2割高く出る設計パラメータ」なので、
// 実測をそこに合わせて上げると、次はさらに高い値を要求される循環になる。
// MEASURE_CURRENT_STEP の「狙いに合わせるなら」はこちらを基準に計算する。
#define CURRENT_BW_TARGET_HZ 700.0f

// ゲインは L と R から実行時に計算する (フラッシュの実測値を使うため)。
//   Kp = L × 2π × f_bw,  Ki = R × 2π × f_bw
#define CURRENT_PI_KP_FROM(l) ((l) * 6.28318531f * CURRENT_BW_HZ)  // [V/A]
#define CURRENT_PI_KI_FROM(r) ((r) * 6.28318531f * CURRENT_BW_HZ)  // [V/(A·s)]

// ---------------------------------------------------------------------------
// 逆起電力・dq干渉のフィードフォワード
// ---------------------------------------------------------------------------
// モータの電圧方程式には、速度に比例する項が3つある:
//
//   Vd = R·Id + L·dId/dt − ω_e·L·Iq
//   Vq = R·Iq + L·dIq/dt + ω_e·L·Id + ω_e·ψm
//                          └───────┘  └─────┘
//                            dq干渉    逆起電力
//
// これらは電流PIから見ると「速度に比例して大きくなる外乱」。いまはPIの積分項が
// 追いかけているが、積分は誤差が出てからでないと動けない。
// **先に計算して足してやれば、PIは「モデルで説明できない残り」だけを相手に
// すればよくなる。** 掛け算4回ぶんのコストしかない。
//
// 効くのは「速さ」と「余裕」であって定常精度ではない (積分がある以上、時間さえ
// あれば定常偏差はどちらでも0になる)。モデルで検証した効果:
//
//   機械角速度   FF無し    FF有り
//     0 rad/s    0.55ms    0.55ms   ← ω_e=0 なので差は出ない
//    80 rad/s    1.35ms    0.55ms
//   160 rad/s    1.55ms    0.55ms   ← **応答が速度に依存しなくなる**
//
// FF有りでは積分項が 0.39V のまま (FF無しは160rad/sで4.87V)。電圧の余裕を
// 積分で食い潰さないので、飽和しにくくなるのも実質的な利点。
//
// **符号を間違えると外乱が倍になる。** 上のモデルで符号を反転させると
// 160 rad/s で 10.3A の偏差が残り指令に到達しなくなった。実機で確認するときは
// STATUS_PRINT の Vq(FF...) を見ること。FFがVqと同符号で、速度とともに
// Vqの大半を占めるようになっていれば正しい。
//
// L は4番で実測済みなので、dq干渉の2項はいますぐ正確に計算できる。
// ψm は MEASURE_MOTOR_PSI で同定する。0 のままだと逆起電力の項だけが効かない
// (dq干渉の項は効く) ので、段階的に入れられる。
#define CURRENT_FF_ENABLE 1

// FFが使ってよい電圧の割合 (変調限界に対して)。
//
// **FF単独で変調限界を超えさせてはいけない。** そうなるとPIは「FFの出しすぎを
// 打ち消す」ためだけに使われ、電流を制御する余地が無くなる。さらに
// FOC_LimitVoltageVector のアンチワインドアップが毎周期 積分項を縮めるので、
// 制御を完全に失う。
//
// 実測 (2026-07-29, ψmを過大に見積もった状態):
//   Vq:+3.78(FF+5.15)/3.78V  ← FF単独で上限超え
//   Iq: -0.24/+0.50A         ← 指令と逆向き
//   peak: 7.99A              ← MAX_CURRENT 7A 超えのスパイク
//
// 逆起電力が本当に電圧を超える速度では、モータはそれ以上回れないのが物理。
// FFを頭打ちにしても物理は変わらないが、**PIが権限を失わずに済む**。
// 残り15%がPIの取り分。
#define CURRENT_FF_MAX_RATIO 0.85f
#define MOTOR_PSI_DEFAULT 0.001854f  // 鎖交磁束 [Wb] ← フラッシュが空のときの既定値

// ψm の同定。**モータが実際に回る。**
//
// 一定速度の定常状態では Vq = R·Iq + ω_e·ψm なので ψm = (Vq - R·Iq)/ω_e。
// L・R のときと同じく2点で測って差を取り、デッドタイムなどの一定オフセットを消す:
//   ψm = ((Vq2 - Vq1) - R(Iq2 - Iq1)) / (ω_e2 - ω_e1)
//
// **これまでの測定と違い、ロータが本当に回る。** 開始前に3秒のカウントダウンを
// 入れてあるので、危険なら電源を切ること。測り終わったら 0 に戻すこと。
#define MEASURE_MOTOR_PSI 0
#define MOTOR_PSI_SPEED1 80.0f   // 1点目の機械角速度 [rad/s]
#define MOTOR_PSI_SPEED2 160.0f  // 2点目。低速だとデッドタイムのオフセットに埋もれる

// ---------------------------------------------------------------------------
// スイッチ校正でモータ定数を自動測定する
// ---------------------------------------------------------------------------
// スイッチを押しながら起動すると、エンコーダ校正に続けて
//   R, L → 電流PIゲインを再計算 → ψm → 角度の遅れ
// を順に実測し、**まとめてフラッシュに保存**する。
// 次回以降の起動ではフラッシュの値が使われるので、config.h の既定値は使われない。
//
// 順番には理由がある:
//   1. エンコーダ校正が先。d軸の位置が分からないと他が測れない
//   2. R,L の測定はPIをバイパスするのでゲイン不要 → ここで測ってゲインを決める
//   3. ψm は速度制御で回すのでゲインが要る → R,L の後
//   4. 角度の遅れは Vd から求めるので ψm が要る → ψm の後
//
// **3以降はモータが実際に回る。** エンコーダ校正も回すので条件は同じ。
// 0 にすると校正コードごと消える (ROMが約4KB減る)。
#define MOTOR_AUTO_CALIBRATION 1

// 角度の遅れを測るときの機械角速度 [rad/s]。
// 速いほど δ が大きく出て精度が上がるが、電圧の天井に当たらない範囲にすること。
#define ANGLE_DELAY_MEASURE_SPEED 120.0f

// ---------------------------------------------------------------------------
// 起動時の診断表示 (校正とは別。毎回走らせたいときだけ 1)
// ---------------------------------------------------------------------------
// d軸はロータの磁束方向なのでトルクが出ない。逆起電力も負荷変動も混ざらない
// 「純粋な電気的応答」だけが測れる。表面磁石型(SPM)なので Ld = Lq、
// PIゲインも共通なので、結果はq軸にそのまま当てはまる。
//
// **測り終わったら 0 に戻すこと** (起動のたびにモータに電流が流れるため)。

// (1) L と R の同定。**PIをバイパスして Vd を直接与える**ので、応答は
//     制御器の挟まらない素の1次系 (時定数 L/R) になり、モデルの仮定が要らない。
//       定常値から R = V / I_ss、63%到達から τ = L/R → L = τ·R
//     電圧を2点 (V と 2V) 振って差を取る。デッドタイムによる電圧誤差
//     (278ns = 母線電圧の0.56% = 12Vで0.067V) はほぼ一定なので、
//       R = (V2 - V1) / (I2 - I1)
//     とすればキャンセルできる。1点だけだと R に10%近い誤差が乗る。
#define MEASURE_MOTOR_RL 0
#define MOTOR_RL_STEP_VOLTS 0.4f   // 1点目の電圧 [V]。2点目はこの2倍
#define MOTOR_RL_ABORT_AMPS 5.0f   // これを超えたら即座に電圧を切る (Rが想定より小さい場合)

// (2) 閉ループの検証。電流指令にステップを入れて Id の応答を見る。
//     (1) でゲインを直したあと、**極とゼロが打ち消せて1次系になったか**を確認する。
#define MEASURE_CURRENT_STEP 0
#define CURRENT_STEP_AMPS 1.0f  // ステップの大きさ [A]

#define BLDC_CAPTURE_SAMPLES 200  // 記録するサンプル数 (200 × 50µs = 10ms)

// ---------------------------------------------------------------------------
// 角度の遅れ補償
// ---------------------------------------------------------------------------
// 制御に使う電気角には、実際のロータ位置に対する**時間遅れ**がある。
// 一定の時間遅れは、回転中は「速度に比例した角度のずれ」として現れる:
//   δ = ω_e × ANGLE_DELAY_S
// ω̂ は分かっているので、推定角をこのぶん進めれば打ち消せる。
//
// 内訳:
//   AS5600 の内部フィルタ  約1.0 ms   ← **支配的**。センサ出力そのものが遅れている
//   演算遅れ (1.5周期)     0.075 ms   サンプル → CCR書き込み → 次周期の中央で効く
//
// 1次フィルタの等速入力に対する遅れはちょうど時定数ぶんなので、この補償は
// 等速回転に対して原理的に正確。加速中は残差が出るが、加速度制限が
// 100 rad/s² なので 1ms では 0.1 rad/s しか変わらず無視できる。
//
// **実測での合わせ方 (STATUS_PRINT の Vd を見る)**
//   角度が合っていれば d軸に必要な電圧は干渉項だけで Vd ≈ −ω_e·L·Iq ≒ 0。
//   ずれていると逆起電力が漏れて Vd ≈ −ω_e·ψm·sin δ が出る。
//   **高速で回して Vd が0に最も近くなる値**を選べばよい。
//   Vd が負に大きい → 遅れ補償が足りない (値を上げる)
//   Vd が正に振れた → 進めすぎ (値を下げる)
//
// **自動測定できる。** 上の関係を解くと、1回の測定で残差から直接求まる:
//   sin δ = (Vd − R·Id + ω_e·L·Iq) / (ω_e·ψm)
//   t_true = t_いま − δ / ω_e
// (検算: 補償前 t=0,120rad/s,Vd=−1.25V → 1.074ms、
//        補償後 t=1.08ms,247rad/s,Vd=+0.01V → 1.077ms。手計算の1.08msと一致)
//
// スイッチを押しながら起動すると測ってフラッシュに保存する。
// ここの値はフラッシュが空のときの既定値。
#define ANGLE_DELAY_DEFAULT 0.00108f

// 電気角のオフセット [rad]
//   エンコーダ校正 (BLDC_SetEncoder) 後は elec_theta = mech_theta * POLE_PAIRS で
//   d軸(ロータ磁束方向)に一致するので通常は0。
//   Iq指令を入れたときにIdが大きく出る場合はここを調整する。
#define ELEC_THETA_OFFSET 0.0f

