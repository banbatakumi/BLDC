// ADC (共通)
// ===========================================================================
// ADC1(相電流) も ADC2(エンコーダ・電源電圧・温度) も 12bit・基準 3.3V。
#define MAX_ADC_VAL 4095           // ADCの最大値(12bit)
#define ADC2VOLT 0.0008058608059f  // ADC値 → 電圧 [V] (3.3V / 4095)

// ===========================================================================
// 保護
// ===========================================================================
#define TEMP_LIMIT 60  // 温度制限 [°C]

#define SUPPLY_VOLTAGE_MIN_LIMIT 7
#define SUPPLY_VOLTAGE_MAX_LIMIT 15

// 電圧が範囲外のまま、この時間 [ms] 続いたときだけ停止する (一瞬の電圧降下・回生スパイク対策)。
#define SUPPLY_VOLTAGE_TRIP_DELAY_MS 500

// 停止後の復帰ヒステリシス [V]。範囲の内側にこれだけ戻るまで再開しない。
#define SUPPLY_VOLTAGE_RECOVER_HYST 0.5f

// ===========================================================================
// 通信
// ===========================================================================
// 状態フレームの送信間隔 [μs]。上位の制御周期 (500us) に合わせる。
// 11バイト = 1Mbps で 110us。ボーレートとセットで決めること。
#define SERIAL_SEND_INTERVAL_US 500

// 無通信でこの時間 [s] が経つと停止モードに入る。上位はこれを停止手段に使っているので短くしない。
#define SERIAL_TIMEOUT_S 0.5f

// 1回の RecvSerial で処理する最大バイト数。
// 上位は 2kHz × 6バイトで送ってくる。メインループが詰まって溜まった分を数フレーム単位で
// 吐き出せるようにしつつ、連続受信でループが戻らなくなるのを防ぐ上限。
#define SERIAL_RX_BYTES_PER_CALL 32

// 上位から受け取る制限値は **トルクのみ** (速度は上位の指令値そのもので決まる)。
// MD は受信値を信用せず、MAX_CURRENT 由来の上限 (Kt × MAX_CURRENT) で頭打ちにし、
// 実際に適用した値を状態フレームの byte9 でエコーバックする。
// 起動直後の既定値は 0 (動かない)。「0 = 無制限」にしてはいけない。
// 速度側は MAX_ANGULAR_SPEED が MD 固定のハード保護として速度指令をクランプする (通信には載せない)。

// printf での状態表示の間隔 [s]。0 で無効 (コードごと削除)。PIDゲイン調整時に 0.5f 程度。
#define STATUS_PRINT_INTERVAL_S 0

// ===========================================================================
// 実行時間プロファイル (DWTサイクルカウンタ)
// ===========================================================================
// 20kHz制御ループの1回あたりの実行時間を実測する。制御周期を上げる/処理を足す前に確認すること。
//   0 : 無効 (コードごと削除)
//   1 : 割り込み全体と呼び出し周期のみ (オーバーヘッド最小)
//   2 : 内訳 (オブザーバ / 電流ループ / 外側ループ) も測る。全体が 0.5µs ほど増える
#define PROFILE_ISR 0

// プロファイルの表示間隔 [s]。0 で表示しない。printf はブロッキングだが、
// 制御ループは割り込み優先度0なので影響を受けない。
#define PROFILE_PRINT_INTERVAL_S 0

// ===========================================================================
// PWM / 制御周期
// ===========================================================================
// TIM1 はセンター揃え。1周期 = 2 × ARR カウント → 72MHz / (2 × 1800) = 20kHz。デューティ = CCR / ARR。
// (詳細は docs/OPTIMIZATION.md)
#define PWM_ARR 1800
#define PWM_FREQ 20000.0f  // PWM周波数 = 電流ループ周波数 [Hz]

// デッドタイム [カウント]。tim.c の sBreakDeadTimeConfig.DeadTime と一致させる。
// DTG = 20, tDTS = 1/72MHz → 278ns。
#define PWM_DEADTIME_COUNTS 20

#define CURRENT_LOOP_DT (1.0f / PWM_FREQ)  // 電流ループ周期 [s] (50µs)

// 外側ループはADC完了割り込みを分周して回す (角速度は分周せず、20kHzのオブザーバから得る)。
#define OUTER_LOOP_DIV 20  // 速度/位置制御 → 1kHz
#define OUTER_LOOP_DT (CURRENT_LOOP_DT * OUTER_LOOP_DIV)

// ---------------------------------------------------------------------------
// デューティの上限
// ---------------------------------------------------------------------------
// ローサイドシャントは低側FETがONの区間しか相電流が流れない。センター揃えではこの区間が
// カウンタ頂点を中心に左右対称に広がり、片側の幅は (PWM_ARR - CCR) カウント。
// サンプリングは頂点付近で行うので、頂点の手前側に次の時間が収まる必要がある:
//   必要 = デッドタイム + アンプ整定 + トリガ前倒し = 20 + 144 + 50 = 214 カウント
//   使える = PWM_ARR - MAX_DUTY_CCR = 216 カウント  ✓
//
// 整定時間 144カウント (2.0µs) の根拠: INA181A1 は帯域 350kHz の1次系 (τ = 455ns)、
// 1%整定 = 4.6τ = 2.1µs、データシート実測 1.6µs typ。**オシロでの実測値ではなく保守側の値。**
// 詰めると高デューティ域だけ電流値が嘘になるので、変更時は docs/OPTIMIZATION.md の
// 「ADCで整定時間を測る」を参照。
#define CURRENT_SENSE_SETTLING_COUNTS 144

// 上限・下限は _Static_assert で使うため、デューティではなく CCR カウント数で定義する。
#define MAX_DUTY_CCR 1584  // 1584 / 1800 = 0.880
#define MIN_DUTY_CCR 36    //   36 / 1800 = 0.020

#define MAX_DUTY ((float)MAX_DUTY_CCR / (float)PWM_ARR)

// 電圧ベクトルの大きさの上限 (対 母線電圧)。三次高調波重畳SVPWMでの相電圧振幅の上限。
#define MAX_MODULATION_RATIO ((MAX_DUTY - 0.5f) * 1.1547005f)

// ===========================================================================
// 電流センシング (ローサイドシャント + INA181A1)
// ===========================================================================
// 回路: CurcuitV4 R16/R24 = 5mΩ, U4/U6 = INA181A1。
// REF は 1k/1k 分圧で 1.65V なので、無電流時の出力は ADC 2048 で正負どちらの電流も読める。
#define SHUNT_RESISTANCE 0.005f  // シャント抵抗 [Ω]
#define CURRENT_AMP_GAIN 20.0f   // INA181A1 のゲイン [V/V]

#define CURRENT_REF_ADC 2048.0f       // 無電流時の出力(理論値) [ADC]
#define CURRENT_OFFSET_TOLERANCE 250  // オフセット校正値の許容ずれ [ADC]

// ADCトリガ位置: カウンタ頂点から何カウント手前で叩くか。
// TIM1_CH4 を PWM2 モードにして CCR4 = PWM_ARR - この値 とし、OC4REF → TRGO2 → ADC1外部トリガ。
// 低側ON区間の中央 (頂点) をまたいでサンプリングし、三角波リプルの平均値を得る。
//   2ch連続変換: トリガから2ch目のサンプリング終了まで 74 + 61.5 = 135.5 ADCサイクル (72MHz)
//   中央に合わせるなら 68 カウント手前だが、整定時間の制約のほうが厳しいので 50 にしている
//   (取得区間の中心は頂点の 18 カウント後ろ。実害なし)。
#define CURRENT_SENSE_TRIG_ADVANCE 50

// トリガから2ch目のサンプリングが終わるまで [カウント]。(61.5+12.5) + 61.5 = 135.5 → 135
#define CURRENT_SENSE_ACQ_COUNTS 135

// --- 設定の整合チェック ---
// PWM周波数・MAX_DUTY・トリガ位置・サンプリング時間は互いに縛り合っており、どれかを触ると
// 電流値だけが静かに壊れる。ビルドで検出する。
// (メッセージがASCIIなのは、GCCが非ASCIIを8進エスケープに潰して読めなくなるため)

// (1) 頂点の手前側: 低側FETがONしてアンプが整定してからトリガが来ること
_Static_assert((PWM_ARR - CURRENT_SENSE_TRIG_ADVANCE) - (MAX_DUTY_CCR + PWM_DEADTIME_COUNTS) >=
                   CURRENT_SENSE_SETTLING_COUNTS,
               "MAX_DUTY_CCR too high: ADC samples before the current amp settles. "
               "Lower MAX_DUTY_CCR or CURRENT_SENSE_TRIG_ADVANCE.");

// (2) 頂点の奥側: 2ch目のサンプリングが終わる前に低側FETがOFFにならないこと
_Static_assert((CURRENT_SENSE_ACQ_COUNTS - CURRENT_SENSE_TRIG_ADVANCE) <=
                   (PWM_ARR - MAX_DUTY_CCR),
               "ADC acquisition runs past the low-side ON window. "
               "Raise CURRENT_SENSE_TRIG_ADVANCE or lower MAX_DUTY_CCR/sampling time.");

// (3) 下限が上限を下回っていること
_Static_assert(MIN_DUTY_CCR >= 0 && MIN_DUTY_CCR < MAX_DUTY_CCR && MAX_DUTY_CCR < PWM_ARR,
               "Duty CCR limits are inconsistent.");

// (4) トリガ位置がカウンタ範囲に収まっていること
_Static_assert(CURRENT_SENSE_TRIG_ADVANCE > 0 && CURRENT_SENSE_TRIG_ADVANCE < PWM_ARR,
               "CURRENT_SENSE_TRIG_ADVANCE out of range.");

// 割り込みがこの時間 [µs] を超えるとデューティの反映が1周期ずれる。
// CCRはプリロード付きで、センター揃えの更新イベントは頂点と谷の両方で起きる。書き込みが
// 谷に間に合わないと次の頂点で反映され、低側ON区間が非対称になってサンプリング点がずれる。
//   使える時間 = 谷までの 25.0µs - 頂点→2ch目変換完了 1.36µs - 割り込み応答 約0.2µs = 23.4µs
// PROFILE_ISR 有効時、irq の最大値がこれを超えると警告が出る。
#define ISR_DEADLINE_US 23.4f

// 電流の符号。シャントはGND側にあり、モータへ流れ出す向き(正)の電流ではアンプ出力が REF より下がる。
// よって「(ADC値 - オフセット) × -1」が相電流になる。
#define CURRENT_SIGN (-1.0f)

// 測定電流のローパス係数 (1.0で無フィルタ)。fc = fs × -ln(1-a) / 2π (fs = 20kHz)
//   a=0.25 → 916Hz,  a=0.5 → 2206Hz,  a=0.8 → 5.1kHz
// 頂点サンプリングなので1サンプルがその周期の平均電流であり、リプル除去は不要。
// 役割はスパイク除去のみで、位相遅れは電流ループ帯域を制限する。
// a=0.5 なら 700Hz に対する位相遅れは 17.6°。
#define CURRENT_LPF_COEF 0.5f

// ===========================================================================
// BLDCのパラメーター
// ===========================================================================
#define POLE_PAIRS 7              // 極対数 (磁石の数/2)
#define MAX_ANGULAR_SPEED 150.0f  // 最大角速度 [rad/s]
#define MAX_ANGULAR_ACCEL 150.0f  // 最大角加速度 [rad/s^2]

// ブレーキモードの境界層幅 [rad/s]。
// 制動電流を -brake_current × sign(ω) にするとv=0付近でチャタリングするので、
// sign の代わりに tanh(ω / この値) を使って境界層内を滑らかに0へつなぐ。
#define BRAKE_BOUNDARY_SPEED_RAD_S 20.0f

// ブレーキモードの不感帯 [rad/s]。tanh は v=0 でも傾きを持つため、静止付近の速度推定の
// 揺らぎが微小トルクのディザになる。この速度未満ではトルクを完全に0にする。
#define BRAKE_DEADBAND_SPEED_RAD_S 2.0f

// ===========================================================================
// 角度追従オブザーバ (2次PLL)
// ===========================================================================
// 推定角 θ̂ を観測角に追従させるループの内部状態として θ̂ と ω̂ を同時に得る。
//   e   = θ_meas - θ̂
//   ω̂ += PLL_KI * e * dt
//   θ̂ += (ω̂ + PLL_KP * e) * dt
// 閉ループは標準2次系で ω_n = √KI, ζ = KP / (2√KI)。ζ=1 (臨界制動) として
// KP = 2·ω_n, KI = ω_n² とするので、調整は PLL_OMEGA_N だけでよい。
// ω_n が大きいほど追従が速いがエンコーダのノイズを拾う。整定時間は約 4/ω_n。
// 周波数誤差からの引き込み上限は PLL_KP 程度なので、PLL_KP ≥ MAX_ANGULAR_SPEED なら
// どの運転速度からでも再ロックできる。
#define PLL_OMEGA_N 900.0f
#define PLL_KP (2.0f * PLL_OMEGA_N)         // 2ζω_n [1/s]
#define PLL_KI (PLL_OMEGA_N * PLL_OMEGA_N)  // ω_n²  [1/s²]

// --- 観測値の棄却条件 ---
// 「観測できない」と「推定がずれている」を区別すること。混ぜると、ロータを急停止させたとき
// θ̂ の自走を異常な観測として棄却し続け、永久にロックが戻らなくなる。

// (a) 飽和の検出 [LSB]。生のADC値がレール付近 (AS5600のアナログ出力の飽和域) なら角度情報が
//     無いので、そのサンプルを弾いて ENCODER_REJECT_MAX サンプルまで外挿する。
#define ENCODER_EDGE_MARGIN_LSB 4
#define ENCODER_REJECT_MAX 1000  // 1000 × 50µs = 50ms

// (b) イノベーション過大 [rad]。0/2π遷移中のグリッチか本当のずれかは1サンプルでは区別できない
//     ので、ENCODER_GLITCH_MAX サンプルまで様子を見て、続くなら棄却をやめてPLLに再ロックさせる。
//     継ぎ目を外挿で渡った直後の実測 emax ≒ 0.09rad に対し約2.7倍の余裕を取ってある
//     (近すぎると偶然の連続超過で再取得モードに入り、速度スパイクが復活する)。
//     グリッチは中間値を拾い最大πになるので 0.25rad でも確実に捕まる。
#define ENCODER_INNOVATION_LIMIT_RAD 0.25f
#define ENCODER_GLITCH_MAX 20  // 20 × 50µs = 1ms

// 速度推定(積分パス)に渡すイノベーションの上限 [rad]。**ロック中のみ適用。**
// ロック中の小さなイノベーションは継ぎ目の段差や外挿誤差であって本物の回転ではない。
// 全量を積分に入れると1回転ごとの速度スパイクになる。比例パスは制限しないので段差は角度補正として吸収される。
// 再取得中に制限すると dω̂/dt が頭打ちになり、急減速に追従できず戻れなくなる。
// 目安: 角加速度 a による定常イノベーションは a / PLL_KI。0.005rad は
// ω_n=900 で 4050 rad/s² 相当。
#define PLL_SPEED_ERROR_LIMIT_RAD 0.005f

// ===========================================================================
// 電流制限・保護
// ===========================================================================
// Id/Iq指令の上限 [A]。トルクの絶対上限 = Kt × MAX_CURRENT。上げるときは次を確認すること:
//   - OVERCURRENT_LIMIT : これより下だと保護が先に飛ぶ。25%の余裕を取る
//   - 電流センスのフルスケール ±16.5A (5mΩ × 20V/V)。OVERCURRENT がここに近いと測定値が飽和する
//   - プロトコルの torque_limit は u8 × 0.001 = 0.255 N・m 天井 (≒ 13.1A 相当)
//   - FET (SSM6K819R ×6) とシャント (1206 5mΩ) の発熱 (TEMP_LIMIT で監視)
#define MAX_CURRENT 10.0f        // Id/Iq指令の上限 [A]
#define OVERCURRENT_LIMIT 15.0f  // 過電流保護のしきい値 [A] (MAX_CURRENT の 1.5倍)

// 連続して何サンプルしきい値を超えたら保護を発動するか (5 → 250µs)。単発ノイズの誤検出防止。
#define OVERCURRENT_TRIP_COUNT 5

// ---------------------------------------------------------------------------
// 電流PI制御のゲイン
// ---------------------------------------------------------------------------
// 設計式: Kp = L × ω_bw, Ki = R × ω_bw。PIのゼロ点 Ki/Kp がプラントの極 R/L を打ち消し、
// 閉ループは帯域 ω_bw の1次系になる。L と R は実行時にフラッシュの実測値から計算する。
// (Kp, Ki を同じ倍率で動かす方式は R/L とのずれを保ったままになるので使わない)
//
// 帯域の上限はプラントではなく位相遅れで決まる (700Hz のとき):
//   1.5周期の演算遅れ 18.9° + 電流LPF 17.6° → 位相余裕 約53°。700Hz 前後が現実的な上限。

// モータの電気的パラメータ (**フラッシュが空のときの既定値**)。
// 通常はスイッチを押しながら起動して自動測定した値がフラッシュに保存され、そちらが優先される。
// 値は 2026-07-29 の実測 (Vd = 0.4V/0.8V の2点、デッドタイム・LPF補正込み)。
#define MOTOR_L_DEFAULT 0.000038f  // 相インダクタンス [H] (38 µH)
#define MOTOR_R_DEFAULT 0.1928f    // 相抵抗 [Ω]

// 電流ループの設計帯域 [Hz]。実測帯域は理想的な極零相殺・遅れ0を仮定した設計値より
// 2〜3割低く出る (700 にして実測 570Hz だったので 850 にしている)。
// 上げるときは MEASURE_CURRENT_STEP で確認し、オーバーシュートが15%を超えたら上げすぎ (現状 2.3%)。
#define CURRENT_BW_HZ 850.0f

// 実際に達成したい閉ループ帯域 [Hz]。CURRENT_BW_HZ (設計パラメータ) とは別物で、
// MEASURE_CURRENT_STEP の「狙いに合わせるなら」の基準になる。
#define CURRENT_BW_TARGET_HZ 700.0f

#define CURRENT_PI_KP_FROM(l) ((l) * 6.28318531f * CURRENT_BW_HZ)  // [V/A]
#define CURRENT_PI_KI_FROM(r) ((r) * 6.28318531f * CURRENT_BW_HZ)  // [V/(A·s)]

// ---------------------------------------------------------------------------
// 逆起電力・dq干渉のフィードフォワード
// ---------------------------------------------------------------------------
//   Vd = R·Id + L·dId/dt − ω_e·L·Iq
//   Vq = R·Iq + L·dIq/dt + ω_e·L·Id + ω_e·ψm
//                          └─ dq干渉 ─┘ └ 逆起電力 ┘
// 速度に比例するこれらの項を先に計算してPIの出力に足し、PIはモデルで説明できない残りだけを担当する。
// 効果は応答が速度に依存しなくなること (モデル検証: 160rad/s で 1.55ms → 0.55ms) と、
// 積分項が電圧余裕を食わないこと。
// **符号を間違えると外乱が倍になる。** 実機では STATUS_PRINT の Vq(FF...) を見て、
// FFがVqと同符号で速度とともに大半を占めていれば正しい。
// ψm が 0 のままだと逆起電力の項だけが効かない (dq干渉の項は効く)。
#define CURRENT_FF_ENABLE 1

// FFが使ってよい電圧の割合 (変調限界に対して)。FF単独で限界を超えると、PIはFFの出しすぎを
// 打ち消すだけになり、アンチワインドアップが積分項を縮め続けて制御を失う。残り15%がPIの取り分。
#define CURRENT_FF_MAX_RATIO 0.85f
#define MOTOR_PSI_DEFAULT 0.001854f  // 鎖交磁束 [Wb] (フラッシュが空のときの既定値)

// ψm の同定。**モータが実際に回る** (開始前に3秒のカウントダウンあり。測り終わったら 0 に戻すこと)。
// 定常状態では Vq = R·Iq + ω_e·ψm。L・R と同様に2点で測り、デッドタイム等の一定オフセットを消す:
//   ψm = ((Vq2 - Vq1) - R(Iq2 - Iq1)) / (ω_e2 - ω_e1)
#define MEASURE_MOTOR_PSI 0
#define MOTOR_PSI_SPEED1 80.0f   // 1点目の機械角速度 [rad/s]
#define MOTOR_PSI_SPEED2 160.0f  // 2点目。低速だとデッドタイムのオフセットに埋もれる

// ---------------------------------------------------------------------------
// スイッチ校正によるモータ定数の自動測定
// ---------------------------------------------------------------------------
// スイッチを押しながら起動すると、エンコーダ校正に続けて
//   R,L → 電流PIゲイン再計算 → ψm → 角度の遅れ
// を順に実測し、まとめてフラッシュに保存する。次回以降はフラッシュの値が使われる。
// 順序の理由: d軸位置が必要なのでエンコーダ校正が先 / R,L はPIをバイパスして測る /
// ψm は速度制御で回すのでゲインが要る / 角度の遅れは Vd から求めるので ψm が要る。
// **ψm 以降ではモータが実際に回る (エンコーダ校正も回る)。**
// 0 にすると校正コードごと消える (ROM 約4KB減)。
#define MOTOR_AUTO_CALIBRATION 1

// 角度の遅れを測るときの機械角速度 [rad/s]。速いほど精度が上がるが、電圧の天井に当たらない範囲にする。
#define ANGLE_DELAY_MEASURE_SPEED 120.0f

