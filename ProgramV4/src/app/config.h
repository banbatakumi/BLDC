// 起動時の診断 (校正とは別。毎回走らせたいときだけ 1。**測り終わったら 0 に戻す**)
// ---------------------------------------------------------------------------
// d軸はトルクが出ず逆起電力も混ざらないので、純粋な電気的応答だけが測れる。
// 表面磁石型(SPM)なので Ld = Lq で、結果はq軸にそのまま当てはまる。

// (1) L と R の同定。PIをバイパスして Vd を直接与え、素の1次系 (時定数 L/R) の応答を見る。
//       定常値から R = V / I_ss、63%到達から τ = L/R
//     電圧を2点 (V と 2V) 振って R = (V2 - V1) / (I2 - I1) とし、デッドタイム誤差
//     (278ns = 12Vで約0.067V) を消す。1点だと R に10%近い誤差が乗る。
#define MEASURE_MOTOR_RL 0
#define MOTOR_RL_STEP_VOLTS 0.4f  // 1点目の電圧 [V]。2点目はこの2倍
#define MOTOR_RL_ABORT_AMPS 5.0f  // これを超えたら即座に電圧を切る

// (2) 閉ループの検証。電流指令にステップを入れて Id の応答を見て、極零相殺できて1次系になったかを確認する。
#define MEASURE_CURRENT_STEP 0
#define CURRENT_STEP_AMPS 1.0f  // ステップの大きさ [A]

#define BLDC_CAPTURE_SAMPLES 200  // 記録するサンプル数 (200 × 50µs = 10ms)

// ---------------------------------------------------------------------------
// 角度の遅れ補償
// ---------------------------------------------------------------------------
// 制御用の電気角には実ロータ位置に対する時間遅れがあり、回転中は δ = ω_e × 遅れ時間 の
// 角度ずれになる。ω̂ は分かっているので、推定角をこのぶん進めて打ち消す。
//   AS5600 の内部フィルタ 約1.0ms (支配的) + 演算遅れ (1.5周期) 0.075ms
// 1次フィルタの等速入力に対する遅れは時定数ぶんなので、等速回転に対しては原理的に正確。
//
// 手動調整: 高速で回して STATUS_PRINT の Vd が0に最も近くなる値を選ぶ。
//   Vd が負に大きい → 補償不足 (上げる) / 正に振れた → 進めすぎ (下げる)
// 自動測定: sin δ = (Vd − R·Id + ω_e·L·Iq) / (ω_e·ψm)、t_true = t_いま − δ / ω_e。
//   スイッチを押しながら起動すると測ってフラッシュに保存する。
// この値はフラッシュが空のときの既定値。
#define ANGLE_DELAY_DEFAULT 0.00108f

// 電気角のオフセット [rad]。エンコーダ校正後は d軸に一致するので通常は0。
// Iq指令でIdが大きく出る場合に調整する。
#define ELEC_THETA_OFFSET 0.0f

